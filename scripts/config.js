/* ================================================================
   ФОРМУЛЫ — все зависимости от уровней апгрейдов

   Собраны здесь, чтобы можно было крутить баланс без правки логики.
   Все принимают объект upgrades { power, aero, fuel, thrust }.
================================================================ */

export const RULES = {
  /**
   * Стартовая скорость ракеты (м/с).
   * Lv1: 26, Lv10: 80.
   */
  launchSpeed: (u) => 20 + u.power * 6,

  /**
   * Максимальное топливо (в секундах буста).
   * Lv1: 2.0с, Lv10: 6.05с.
   */
  maxFuel: (u) => 1.8 + (u.fuel - 1) * 1.758,

  /**
   * Ускорение от тяги (м/с² вдоль носа).
   * Lv1: 12, Lv10: 48.
   */
  thrustAcc: (u) => 12 + (u.thrust - 1) * 3.0,

  /**
   * Коэффициент сопротивления воздуха в зависимости от угла атаки.
   *
   *   aligned   — нос строго по потоку (α=0°)      → минимум
   *   broadside — боком к потоку (α=90°)            → максимум
   *   backward  — соплом вперёд (α=180°)            → среднее
   *   aeroScale — как апгрейд «Аэродинамика» снижает всё это
   *
   * Кривая: квадратичная по cos(α), проходит точно через три точки.
   * Физический смысл: у ракеты острый нос и тупое днище, поэтому
   * минимум — «по потоку», максимум — «боком», промежуток — «спиной».
   *
   * [типично] aligned 0.0020–0.0035, broadside 0.012–0.020,
   *           backward 0.004–0.008, aeroScale 0.25–0.5.
   */
  drag: {
    aligned: 0.0025,
    broadside: 0.0155,
    backward: 0.0055,
    aeroScale: 0.45,
  },

  /**
   * Cd как функция угла атаки α (радианы).
   * @param {{aero:number}} u  — уровни апгрейдов
   * @param {number} alpha     — угол между носом и скоростью (0..π)
   */
  dragCoefAtAngle: (u, alpha) => {
    const D = RULES.drag
    const c = Math.cos(alpha)
    const a = D.broadside
    const b = (D.aligned - D.backward) / 2
    const c2 = D.aligned - a - b
    const base = a + b * c + c2 * c * c
    const scale = 1 / (1 + (u.aero - 1) * D.aeroScale)
    return base * scale
  },

  airDensity: (y) => Math.exp(-Math.max(0, y) / GAME.airHeight),
  upgradeCost: (u, lvl) =>
    Math.floor(u.base * Math.pow(u.growth * GAME.upgrade_cost_diff, lvl - 1)),
}

